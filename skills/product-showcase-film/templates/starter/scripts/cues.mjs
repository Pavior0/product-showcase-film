#!/usr/bin/env node
/**
 * Storyboard → absolute cue timestamps (out/cues.json). If sfx/<name>.wav files exist,
 * also writes out/mix.sh: an ffmpeg adelay+amix graph that lays every cue at its time,
 * then muxes onto the silent render. No SFX files → nothing to mix; the film stays silent.
 *
 *   node scripts/cues.mjs            # cues.json (+ mix.sh if sfx/ has files)
 *   sh out/mix.sh out/film-1080p.mp4 out/film-1080p-sfx.mp4
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { transform } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(root, "src/storyboard.ts"), "utf8");
const { code } = await transform(src, { loader: "ts", format: "esm" });
const tmp = path.join(root, "out", ".storyboard.mjs");
fs.mkdirSync(path.dirname(tmp), { recursive: true });
fs.writeFileSync(tmp, code);
const sb = await import(pathToFileURL(tmp).href);
fs.unlinkSync(tmp);

const cues = [];
for (const p of sb.placeScenes(sb.scenes)) {
  for (const c of p.scene.cues) {
    const n = c.count ?? 1;
    for (let i = 0; i < n; i++) {
      const t = p.start + c.at + i * (c.every ?? 0);
      cues.push({ t: Number(t.toFixed(4)), frame: Math.round(t * sb.film.fps), scene: `${p.index}:${p.scene.id}`, id: n > 1 ? `${c.id}#${i}` : c.id, sfx: c.sfx ?? null });
    }
  }
}
cues.sort((a, b) => a.t - b.t);
const outFile = path.join(root, "out", "cues.json");
fs.writeFileSync(outFile, JSON.stringify({ film: sb.film, duration: sb.totalDuration(sb.scenes), cues }, null, 2));
console.log(`wrote ${path.relative(root, outFile)}: ${cues.length} cues, ${cues.filter((c) => c.sfx).length} with sfx`);

const sfxDir = path.join(root, "sfx");
const have = fs.existsSync(sfxDir) ? new Set(fs.readdirSync(sfxDir).filter((f) => f.endsWith(".wav")).map((f) => f.slice(0, -4))) : new Set();
const used = cues.filter((c) => c.sfx && have.has(c.sfx));
if (!used.length) {
  console.log("no sfx/<name>.wav files found → render stays silent (see README: Audio).");
  process.exit(0);
}
const inputs = [];
const chains = [];
used.forEach((c, i) => {
  inputs.push(`-i sfx/${c.sfx}.wav`);
  const ms = Math.round(c.t * 1000);
  chains.push(`[${i + 1}:a]adelay=${ms}|${ms}[a${i}]`);
});
const graph = `${chains.join(";")};${used.map((_, i) => `[a${i}]`).join("")}amix=inputs=${used.length}:normalize=0[sfx]`;
const sh = `#!/bin/sh
# generated by scripts/cues.mjs — lays ${used.length} sfx hits at their cue times
set -e
IN="\${1:-out/film-1080p.mp4}"; OUT="\${2:-out/film-1080p-sfx.mp4}"
ffmpeg -y -i "$IN" ${inputs.join(" ")} -filter_complex "${graph}" -map 0:v -map "[sfx]" -c:v copy -c:a aac -b:a 192k -shortest "$OUT"
`;
fs.writeFileSync(path.join(root, "out", "mix.sh"), sh);
console.log(`wrote out/mix.sh (${used.length} hits)`);
